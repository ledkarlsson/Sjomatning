const { app, BrowserWindow, ipcMain, session } = require('electron')
const path = require('node:path')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
const { createLibraryStore } = require('../src/library-store')
app.setPath('userData', path.join(app.getPath('temp'), `sjomatning-library-ui-${process.pid}`))
app.whenReady().then(async () => {
  const store = createLibraryStore(path.join(app.getPath('userData'), 'library'))
  ipcMain.handle('library:list', () => store.list())
  ipcMain.handle('library:update', (_event, id, changes) => store.update(id, changes))
  ipcMain.handle('files:launch-pdf', () => null)
  ipcMain.handle('app:info', () => ({ version: 'test', buildDate: '2026-09-13' }))
  ipcMain.handle('roxen:water-level', (_event, date) => ({ ok: true, data: { date: date || '2026-09-13', level: 33 } }))
  ipcMain.handle('live:start', () => ({ id: 'simulation', folder: 'Testsession' }))
  const samples=[]
  ipcMain.handle('live:append', (_event,data) => {samples.push(data);return true})
  ipcMain.handle('live:stop', () => true)
  await session.defaultSession.protocol.handle('https', () => new Response('<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#c5dfeb"/></svg>', { headers: { 'content-type': 'image/svg+xml' } }))
  const win = new BrowserWindow({ show: false, width: 1440, height: 900, webPreferences: { preload: path.resolve('src/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  const run = source => win.webContents.executeJavaScript(source)
  const wait = async source => {
    for (let i = 0; i < 200; i++) { if (await run(source)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
    throw new Error('Timed out: ' + source)
  }
  await win.loadFile(path.resolve('src/index.html'))
  await wait(`document.querySelector('#zoomValue').textContent.includes('Z')`)
  await run(`document.querySelector('#simulationGpsOnly').checked=true;document.querySelector('#simulationSpeed').value='60';document.querySelector('#startSimulator').click()`)
  await wait(`document.querySelector('#liveBadge').textContent==='Simulerar'`)
  await new Promise(resolve=>setTimeout(resolve,2200))
  assert.ok(samples.filter(s=>s.point).length>=2)
  assert.ok(samples.every(s=>s.point?.depth===null))
  assert.match(await run(`document.querySelector('#mapReadout').textContent`),/5.0 kn/)
  assert.match(await run(`document.querySelector('#mapReadout').textContent`),/Kurs över grund/)
  assert.ok(await run(`Number(document.querySelector('#overlayCanvas').dataset.renderedPoints)>0`))
  assert.ok(await run(`(()=>{const c=document.querySelector('#overlayCanvas');return Math.abs(Number(c.dataset.boatX)-c.width/2)<2 && Math.abs(Number(c.dataset.boatY)-c.height/2)<2})()`))
  await run(`(()=>{const c=document.querySelector('#overlayCanvas');c.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,pointerId:1,clientX:400,clientY:300}));c.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,pointerId:1,clientX:500,clientY:300}));c.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerId:1,clientX:500,clientY:300}))})()`)
  assert.equal(await run(`document.querySelector('#followBoat').textContent`),'Följ båt')
  await run(`document.querySelector('#followBoat').click()`)
  assert.equal(await run(`document.querySelector('#followBoat').textContent`),'Följer båt')
  await run(`document.querySelector('#stopCapture').click()`)
  await wait(`document.querySelector('#liveBadge').textContent==='Frånkopplad'`)
  const {parseTextTrack}=await import('../src/track-parser.mjs')
  const text=samples.filter(s=>s.point).map(({point:p})=>[p.date,p.time,p.lat,p.lon,p.speed,p.depth].join(',')).join('\n')
  assert.equal(parseTextTrack(text,'gps.csv').points.length,samples.length)
  assert.deepEqual(errors,[])
  console.log('PASS: GPS-only simulator, live speed/course, rendered track, clean stop, CSV reimport')
  app.quit()
}).catch(error=>{console.error(error);app.exit(1)})

