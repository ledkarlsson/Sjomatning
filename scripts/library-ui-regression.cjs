const { app, BrowserWindow, ipcMain, session } = require('electron')
const path = require('node:path')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
const { createLibraryStore } = require('../src/library-store')
app.setPath('userData', path.join(app.getPath('temp'), `sjomatning-library-ui-${process.pid}`))
app.whenReady().then(async () => {
  const store = createLibraryStore(path.join(app.getPath('userData'), 'library'))
  await store.persist([
    { name: 'Båt Å.csv', bytes: Buffer.from('2026-09-13,10:00:00,58.5,15.6,3,5\n2026-09-13,10:00:01,58.50001,15.60001,3,5') },
    { name: 'Båt Ö.csv', bytes: Buffer.from('2026-09-13,10:00:00,58.5,15.6,3,6\n2026-09-13,10:00:01,58.50001,15.60001,3,6') }
  ])
  ipcMain.handle('library:list', () => store.list())
  ipcMain.handle('library:update', (_event, id, changes) => store.update(id, changes))
  let cloudRequest
  ipcMain.handle('library:sync-cloud', (event, options) => {
    cloudRequest=options
    event.sender.send('library:sync-progress',{current:1,total:2,name:'Båt Å.csv'})
    return {uploaded:2,updated:0,unchanged:0,skipped:0,errors:[]}
  })
  ipcMain.handle('files:launch-pdf', () => null)
  ipcMain.handle('app:info', () => ({ version: 'test', buildDate: '2026-09-13' }))
  ipcMain.handle('roxen:water-level', (_event, date) => ({ ok: true, data: { date: date || '2026-09-13', level: 33 } }))
  ipcMain.handle('live:start', () => ({ id: 'simulation', folder: 'Testsession' }))
  ipcMain.handle('live:append', () => true)
  ipcMain.handle('live:stop', () => true)
  await session.defaultSession.protocol.handle('https', () => new Response('<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#c5dfeb"/></svg>', { headers: { 'content-type': 'image/svg+xml' } }))
  const win = new BrowserWindow({ show: false, width: 1440, height: 900, webPreferences: { preload: path.resolve('src/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  const run = source => win.webContents.executeJavaScript(source)
  const wait = async source => {
    for (let i = 0; i < 200; i++) { if (await run(source)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
    throw new Error('Timed out: ' + source)
  }
  await win.loadFile(path.resolve('src/index.html'))
  await wait(`document.querySelectorAll('[data-folder-track]').length === 2`)
  assert.equal(await run(`document.querySelector('#cloudSyncPanel').classList.contains('hidden')`),false)
  await run(`document.querySelector('#syncCloudLibrary').click()`)
  assert.match(await run(`document.querySelector('#cloudSyncStatus').textContent`),/Ange din åtkomstnyckel/)
  await run(`localStorage.setItem('calibration:test.pdf:123',JSON.stringify([{nx:0,ny:0,lat:58,lon:15}])); document.querySelector('#cloudSyncToken').value='test-only'; document.querySelector('#syncCloudLibrary').click()`)
  await wait(`document.querySelector('#cloudSyncStatus').textContent.includes('Synkningen är klar')`)
  assert.equal(cloudRequest.token,'test-only')
  assert.equal(cloudRequest.calibrations['calibration:test.pdf:123'][0].lat,58)
  assert.equal(await run(`document.querySelector('#cloudSyncToken').value`),'')
  assert.equal(await run(`document.querySelector('#syncCloudLibrary').disabled`),false)
  await wait(`document.querySelector('#toggleTracksPanel').textContent === 'Visa spår (2 spår i området · 0 visas · 2 dolt)'`)
  assert.equal(await run(`document.querySelectorAll('[data-log]:checked').length`), 0, 'library tracks load hidden before any visibility toggle')
  assert.equal(await run(`document.querySelector('#openPdf')`), null)
  await run(`document.querySelector('#showAllTracks').click()`)
  await wait(`document.querySelectorAll('[data-log]:checked').length === 2`)
  await run(`for (let i=0; i<20; i++) document.querySelector('#zoomIn').click()`)
  await wait(`document.querySelector('#logsMapSummary').textContent.startsWith('0 spår i området')`)
  assert.equal(await run(`document.querySelector('#folderTrackList').textContent.includes('Övriga spår')`), false)
  await run(`document.querySelector('#fitView').click()`)
  await wait(`document.querySelector('#logsMapSummary').textContent.startsWith('2 spår i området')`)
  assert.equal(await run(`document.querySelector('#toggleTracksPanel').textContent`), 'Dölj spår (2 spår i området · 2 visas · 0 dolt)')
  await run(`document.querySelector('#openTracksPanel').click()`)
  assert.equal(await run(`getComputedStyle(document.querySelector('#logsPanel')).display === 'none'`), false)
  assert.equal(await run(`document.querySelector('#logsPanel').closest('#viewport') !== null`), true)
  assert.equal(await run(`document.querySelector('#logsPanel').textContent.includes('Importerade körningar')`), false)
  assert.match(await run(`document.querySelector('#logsPanelHelp').textContent`), /Tekniska verken/)
  assert.equal(await run(`document.title`), 'Sjömätning vtest - 2026-09-13')
  const { fitBounds, ROXEN_BOUNDS, geoToMapPixel } = await import('../src/web-map.mjs')
  const rect = await run(`(() => { const r=document.querySelector('#overlayCanvas').getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height} })()`)
  const pixel = geoToMapPixel(fitBounds(ROXEN_BOUNDS, rect.width, rect.height), 58.5, 15.6)
  await run(`document.querySelector('#overlayCanvas').dispatchEvent(new MouseEvent('click', { bubbles:true, clientX:${rect.x+pixel.x}, clientY:${rect.y+pixel.y} }))`)
  assert.equal(await run(`document.querySelector('#editorDialog').open`), true)
  await run(`document.querySelector('#editorDialog').close()`)
  await run(`document.querySelector('#colorMode').click()`)
  assert.equal(await run(`document.querySelector('#colorMode').textContent`), 'Färg: spår')
  assert.equal(await run(`document.querySelectorAll('[data-legend-track]').length`), 2)
  await run(`document.querySelector('[data-legend-track="0"]').click()`)
  assert.equal(await run(`document.querySelector('[data-legend-track="0"]').classList.contains('muted-track')`), true)
  assert.equal(await run(`document.querySelectorAll('[data-log]:checked').length`), 1)
  await run(`document.querySelector('[data-legend-track="0"]').click(); document.querySelector('#legendHideAll').click()`)
  assert.equal(await run(`document.querySelectorAll('[data-log]:checked').length`), 0)
  assert.equal(await run(`document.querySelector('#toggleTracksPanel').textContent`), 'Visa spår (2 spår i området · 0 visas · 2 dolt)')
  assert.equal(await run(`document.querySelectorAll('[data-legend-track]').length`), 2)
  await run(`document.querySelector('#legendShowAll').click()`)
  await wait(`document.querySelectorAll('[data-log]:checked').length === 2`)
  await run(`document.querySelector('#toggleTracksPanel').click()`)
  assert.equal(await run(`document.querySelectorAll('[data-log]:checked').length`), 0)
  assert.equal(await run(`document.querySelector('#toggleTracksPanel').textContent`), 'Visa spår (2 spår i området · 0 visas · 2 dolt)')
  assert.equal(await run(`document.querySelector('#logsPanel').classList.contains('hidden')`), false)
  await run(`document.querySelector('#toggleTracksPanel').click()`)
  await wait(`document.querySelectorAll('[data-log]:checked').length === 2`)
  const zoomBeforePanelWheel = await run(`document.querySelector('#zoomValue').textContent`)
  assert.equal(await run(`document.querySelector('#logsPanel').dispatchEvent(new WheelEvent('wheel', {bubbles:true, cancelable:true, deltaY:100}))`), true)
  assert.equal(await run(`document.querySelector('#zoomValue').textContent`), zoomBeforePanelWheel)
  await fs.mkdir('tmp', { recursive: true })
  await new Promise(resolve => setTimeout(resolve, 500))
  await fs.writeFile('tmp/track-panel-ui.png', (await win.webContents.capturePage()).toPNG())
  await run(`document.querySelector('#compareTracks').click()`)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`), /1,00 m/)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`), /2 \/ 2 \(100,00 %\)/)
  await run(`document.querySelector('#comparisonScope').value='selected'; document.querySelector('#comparisonScope').dispatchEvent(new Event('change'))`)
  assert.equal(await run(`document.querySelectorAll('[data-comparison-select]:checked').length`), 2)
  await run(`document.querySelector('[data-comparison-select]').click()`)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`), /Välj minst två/)
  await run(`document.querySelector('[data-comparison-select]').click(); document.querySelector('[data-matches]').click()`)
  assert.equal(await run(`document.querySelector('#editorDialog').open`), false)
  assert.equal(await run(`document.querySelector('#returnComparison').classList.contains('hidden')`), false)
  await run(`document.querySelector('#returnComparison').click(); document.querySelector('#comparisonRadius').value='7'; document.querySelector('#comparisonRadius').dispatchEvent(new Event('change')); document.querySelector('[data-compare-edit]').click(); document.querySelector('#backComparison').click()`)
  assert.equal(await run(`document.querySelector('#comparisonRadius').value`), '7')
  assert.equal(await run(`document.querySelector('#comparisonScope').value`), 'selected')
  await new Promise(resolve => setTimeout(resolve, 200))
  await fs.writeFile('tmp/comparison-ui.png', (await win.webContents.capturePage()).toPNG())
  await run(`document.querySelector('#referenceTrack').value='0'; document.querySelector('#referenceTrack').dispatchEvent(new Event('change')); document.querySelector('[data-compare-edit]').click()`)

  await run(`const input = document.querySelector('[data-point="0"][data-field="depth"]'); input.value='7'; input.dispatchEvent(new Event('change'))`)
  await wait(`document.querySelector('[data-point="0"][data-field="depth"]').value === '7'`)
  let files = await store.list()
  assert.equal(files[1].edits.points[0].depth, 7)
  assert.match(files[1].bytes.toString(), /,3,6/)
  await run(`document.querySelector('#editorDialog').close(); document.querySelector('[data-rename-track="1"]').click(); document.querySelector('#newFileName').value='Ändrad båt'; document.querySelector('#renameForm').requestSubmit()`)
  await wait(`!document.querySelector('#editorDialog').open`)
  assert.match(await run(`document.querySelector('#folderTrackList').textContent`), /Ändrad båt.csv/)
  await win.reload()
  await wait(`document.querySelectorAll('[data-folder-track]').length === 2`)
  await run(`document.querySelector('#showAllTracks').click()`)
  await wait(`document.querySelectorAll('[data-log]:checked').length === 2`)
  await run(`document.querySelector('[data-table-log="1"]').click()`)
  assert.equal(await run(`document.querySelector('[data-field="depth"]').value`), '7')
  await run(`document.querySelector('#editorDialog').close(); window.confirm = () => true; document.querySelector('[data-restore-log="1"]').click()`)
  await wait(`document.querySelector('[data-depth-adjustment="1"]').value === '0.00'`)
  // Wait for the async index write by reading through the serialized store.
  await new Promise(resolve => setTimeout(resolve, 150))
  files = await store.list()
  assert.equal(files[1].edits, null)
  await run(`document.querySelector('[data-table-log="1"]').click()`)
  assert.equal(await run(`document.querySelector('[data-field="depth"]').value`), '6')
  await run(`document.querySelector('#editorDialog').close(); document.querySelector('#hideAllTracks').click()`)
  assert.equal(await run(`document.querySelectorAll('[data-log]:checked').length`), 0)
  assert.equal(await run(`document.querySelector('#toggleTracksPanel').textContent`), 'Visa spår (2 spår i området · 0 visas · 2 dolt)')
  await run(`document.querySelector('#waterLevelPanel').open=true; document.querySelector('#waterLevelDate').value='2026-09-12'; document.querySelector('#waterLevelDate').dispatchEvent(new Event('change'))`)
  await wait(`document.querySelector('#waterLevelStatus').textContent.includes('12 september')`)
  assert.match(await run(`document.querySelector('#waterLevelStatus').textContent`), /Hydrographica/)
  await run(`document.querySelector('#simulatorPanel').open=true; document.querySelector('#startSimulator').click()`)
  await wait(`document.querySelector('#mapReadout').textContent.includes('5.0 kn')`)
  await fs.mkdir('tmp', { recursive: true })
  await fs.writeFile('tmp/library-ui.png', (await win.webContents.capturePage()).toPNG())
  await run(`document.querySelector('#stopCapture').click()`)
  await wait(`document.querySelector('#mapReadout').classList.contains('hidden')`)
  assert.deepEqual(errors, [])
  console.log('PASS: library rename, show/hide all, color mode, comparison, point editing, restart, original restore, automatic water level, simulator map readout')
  app.quit()
}).catch(error => { console.error(error); app.exit(1) })
