const {app,BrowserWindow,ipcMain,session}=require('electron')
const fs=require('node:fs/promises'),path=require('node:path'),assert=require('node:assert/strict')
app.setPath('userData',path.join(app.getPath('temp'),'sjomatning-seaclear-'+process.pid))
app.whenReady().then(async()=>{
 const root='testdata/fältmanus-seaclear'
 const read = async filePath => ({id:path.basename(filePath),name:path.basename(filePath),relativePath:path.basename(filePath),path:filePath,bytes:await fs.readFile(filePath)})
 const inputs=[]
 for(const name of await fs.readdir(root))if(/\.(wci|kap|bsb)$/i.test(name))inputs.push(await read(path.join(root,name)))
 const files=await require('../src/bsb-index').expandChartIndexes(inputs,read)
 assert.equal(files.length,10)
 const rows=Array.from({length:200000},(_,i)=>`2026-09-13,10:00:00,${58.49+(i%1000)*.000001},${15.6+Math.floor(i/1000)*.000001},3,${i===100000?1:5}`)
 files.push({id:'large',name:'Stort spår.csv',relativePath:'Stort spår.csv',bytes:Buffer.from(rows.join('\n'))})
 ipcMain.handle('library:list',()=>files)
 ipcMain.handle('files:launch-pdf',()=>null)
 ipcMain.handle('app:info',()=>({version:'test',buildDate:'test'}))
 ipcMain.handle('roxen:water-level',()=>({ok:false}))
 await session.defaultSession.protocol.handle('https',()=>new Response('',{status:503}))
 const win=new BrowserWindow({show:false,width:1440,height:900,webPreferences:{preload:path.resolve('src/preload.js'),sandbox:true,contextIsolation:true,backgroundThrottling:false}})
 const errors=[];win.webContents.on('console-message',event=>{if(event.level==='error'&&!event.message.includes('503'))errors.push(event.message)})
 const run=source=>win.webContents.executeJavaScript(source)
 const wait=async source=>{for(let i=0;i<600;i++){if(await run(source))return;await new Promise(r=>setTimeout(r,50))}throw new Error('Timed out: '+source)}
 await win.loadFile(path.resolve('src/index.html'))
 await wait(`document.querySelectorAll('[data-locate-pdf]').length===10`)
 assert.equal(await run(`document.querySelectorAll('[data-locate-pdf]:disabled').length`),0)
 await run(`document.querySelector('#showAllTracks').click()`)
 await wait(`document.querySelectorAll('[data-log]:checked').length===1`)
 await run(`document.querySelector('#showSweden').click()`)
 await wait(`Number(document.querySelector('#overlayCanvas').dataset.renderedPoints)<100`)
 const count=await run(`Number(document.querySelector('#overlayCanvas').dataset.renderedPoints)`)
 assert.ok(count>0 && count<100,'200,000 points use a bounded overview')
 for(const index of [0,2]) {
   await run(`document.querySelector('[data-locate-pdf="${index}"]').click()`)
   await wait(`document.querySelector('#toggleManuscripts').getAttribute('aria-pressed')==='true'`)
   await wait(`document.querySelector('#pdfCanvas').dataset.rasterCharts?.split(',').includes(${JSON.stringify(files[index].id)})`)
 }
 await fs.mkdir('tmp',{recursive:true})
 await fs.writeFile('tmp/seaclear-ui.png',(await win.webContents.capturePage()).toPNG())
 assert.deepEqual(errors,[])
 console.log('PASS: 10 SeaClear charts, WCI/KAP rendering offline, 200,000-point overview rendered as '+count+' points')
 app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
