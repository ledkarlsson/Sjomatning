const { app, BrowserWindow, ipcMain, session } = require('electron')
const path = require('node:path')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
const { createLibraryStore } = require('../src/library-store')
app.setPath('userData', path.join(app.getPath('temp'), `sjomatning-library-ui-${process.pid}`))
app.whenReady().then(async () => {
  const store = createLibraryStore(path.join(app.getPath('userData'), 'library'))
  await store.persist([
    { name: '20260913_33.00_Båt_Granholmen.csv', bytes: Buffer.from('2026-09-13,10:00:00,58.5,15.6,3,5\n2026-09-13,10:00:01,59.5,16.6,3,5') },
    { name: '20260913_33.00_Båt_Granholmen.txt', bytes: Buffer.from('2026-09-13,10:00:00,58.5,15.6,3,6\n2026-09-13,10:00:01,59.5,16.6,3,6') },
    { name: 'Utanför.csv', bytes: Buffer.from('2026-09-13,10:00:00,59.5,16.6,3,7') }
  ])
  ipcMain.handle('library:list', () => store.list())
  ipcMain.handle('library:update', (_event, id, changes) => store.update(id, changes))
  ipcMain.handle('files:launch-pdf', () => null)
  ipcMain.handle('app:info', () => ({ version: 'test', buildDate: '2026-09-13' }))
  ipcMain.handle('roxen:water-level', (_event, date) => ({ ok: true, data: { date: date || '2026-09-13', level: 33 } }))
  ipcMain.handle('live:start', () => ({ id: 'simulation', folder: 'Testsession' }))
  ipcMain.handle('live:append', () => true)
  ipcMain.handle('live:stop', () => true)
  await session.defaultSession.protocol.handle('https', () => new Response('<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#c5dfeb"/></svg>', { headers: { 'content-type': 'image/svg+xml' } }))
  const win = new BrowserWindow({ show: false, width: 1440, height: 900, webPreferences: { preload: path.resolve('src/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  const run = source => win.webContents.executeJavaScript(source)
  const wait = async source => {
    for (let i = 0; i < 200; i++) { if (await run(source)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
    throw new Error('Timed out: ' + source)
  }
  await win.loadFile(path.resolve('src/index.html'))
  await wait(`document.querySelectorAll('[data-folder-track]').length === 3`)
  await run(`document.querySelector('#showAllTracks').click()`)
  await wait(`document.querySelectorAll('[data-log]:checked').length === 2`)
  await run(`document.querySelector('#compareTracks').click()`)
  assert.equal(await run(`document.querySelectorAll('#referenceTrack option').length`),2)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`),/1 \/ 1/)
  assert.equal(await run(`document.querySelector('#comparisonResults').textContent.includes('Utanför')`),false)
  await run(`document.querySelector('#comparisonScope').value='all';document.querySelector('#comparisonScope').dispatchEvent(new Event('change'))`)
  assert.equal(await run(`document.querySelectorAll('#referenceTrack option').length`),3)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`),/2 \/ 2/)
  await run(`document.querySelector('#comparisonScope').value='selected';document.querySelector('#comparisonScope').dispatchEvent(new Event('change'))`)
  assert.equal(await run(`document.querySelectorAll('#referenceTrack option').length`),2)
  assert.match(await run(`document.querySelector('#editorContent').textContent`),/Möjliga filvarianter/)
  await run(`document.querySelector('#comparisonRadius').value='0';document.querySelector('#comparisonRadius').dispatchEvent(new Event('change'))`)
  assert.match(await run(`document.querySelector('#comparisonResults').textContent`),/mellan 1 och 100/)
  await run(`document.querySelector('#comparisonRadius').value='10';document.querySelector('#comparisonRadius').dispatchEvent(new Event('change'))`)
  win.show()
  await new Promise(resolve => setTimeout(resolve,500))
  await fs.mkdir('tmp',{recursive:true})
  await fs.writeFile('tmp/feedback-comparison.png',(await win.webContents.capturePage()).toPNG())
  assert.deepEqual(errors,[])
  console.log('PASS: viewport clips both tracks, all scope includes outside points, explicit selection, variant groups, radius validation')
  app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
